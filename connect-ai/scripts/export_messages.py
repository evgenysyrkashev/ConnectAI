"""Render the final customer messages to docs/MESSAGES.md.

    python -m scripts.export_messages        # LLM_MODE=vertex (in .env) writes the real model's intros; fake otherwise

One message per language for each template, the inform and permission messages, WhatsApp and SMS texts, and the
applied / declined / stopped follow-ups. Uses a synthetic business, never kit data.
"""

from __future__ import annotations

from pathlib import Path
from types import SimpleNamespace

from app.core import compose
from app.core.channel import sms_text
from app.core.i18n import holiday_name
from app.core.models import Contact, DateItem, OutboundMessage
from app.core.prompts import IntroInput
from app.core.templates import TEMPLATES
from app.core.wa_templates import BUTTONS, render_body, wa_content_fitted
from app.server.services.campaigns import generate_intro, intro_facts

OUT = Path(__file__).resolve().parents[1] / "docs" / "MESSAGES.md"
SENDER = "ConnectAI (demo)"
LANGS = [("fi", "FI", "Finnish"), ("sv", "SE", "Swedish"), ("nb", "NO", "Norwegian"), ("en", "FI", "English")]
CAL = {
    "FI": {"XMAS_EVE": ("Jouluaatto", "Christmas Eve"), "NYE": ("Uudenvuodenaatto", "New Year's Eve")},
    "SE": {"XMAS_EVE": ("Julafton", "Christmas Eve"), "NYE": ("Nyårsafton", "New Year's Eve")},
    "NO": {"XMAS_EVE": ("Julaften", "Christmas Eve"), "NYE": ("Nyttårsaften", "New Year's Eve")},
}
LISTINGS = [
    {"status": "LIVE", "publisherId": p, "typicalUpdateSpeedSeconds": s}
    for p, s in [("GOOGLEMYBUSINESS", 120), ("APPLE", 172800), ("FONECTA_FINDER", 600)]
]


def _items(country: str, lang: str, *, ask_item: bool = False) -> list[DateItem]:
    def name(key):
        n_local, n_en = CAL[country][key]
        return holiday_name(country, key, "", lang, {"name_local": n_local, "name_en": n_en}, None)

    items = [
        DateItem(
            date="2026-12-24",
            day_key="XMAS_EVE",
            day_name=name("XMAS_EVE"),
            shown_hours="08:00-20:00",
            shown_source="regular",
            suggested_hours="closed",
            basis="LAST_YEAR",
            reason=compose.reason_for("LAST_YEAR", {"last_year_hours": "closed"}, lang),
            est_views=120,
            priority=96,
        ),
        DateItem(
            date="2026-12-31",
            day_key="NYE",
            day_name=name("NYE"),
            shown_hours="08:00-20:00",
            shown_source="regular",
            suggested_hours=None if ask_item else "10:00-14:00",
            basis=None if ask_item else "PEERS",
            reason="" if ask_item else compose.reason_for("PEERS", None, lang),
            est_views=90,
            priority=70,
        ),
    ]
    return items


def _msg(
    template_id: str, kind: str, lang: str, country: str, intro: str, short: str, subject: str, **kw
) -> OutboundMessage:
    base = {
        "id": "0" * 16,
        "campaign_id": "c",
        "entity_id": f"{country}-DEMO",
        "entity_name": "Kahvila Testi",
        "country": country,
        "template_id": template_id,
        "kind": kind,
        "language": lang,
        "mode": "ask",
        "contact_email": "owner@example.com",
        "to_email": None,
        "subject": subject,
        "intro": intro,
        "intro_source": "llm",
        "body": "",
        "items": [],
        "weekly_shown": None,
        "status": "draft",
        "created_at": "2026-11-06T10:00:00Z",
        "short": short,
    }
    base.update(kw)
    return OutboundMessage(**base)


def render(llm) -> str:
    deps = SimpleNamespace(llm=llm)
    out = [
        "# Final customer messages",
        "",
        (
            "Generated by `python -m scripts.export_messages` from the same code the app uses. Intros come from "
            f"{'the real model' if type(llm).__name__ == 'VertexLlm' else 'the fake LLM (deterministic text)'}; "
            "all dates, hours and instructions are written by code."
        ),
        "",
    ]
    week = {d: "09:00-17:00" for d in ("monday", "tuesday", "wednesday", "thursday", "friday")} | {
        "saturday": "closed",
        "sunday": "closed",
    }
    for lang, country, label in LANGS:
        contact = Contact(
            entity_id=f"{country}-DEMO",
            first_name="Maria",
            preferred_channel="EMAIL",
            language=lang,
            email="owner@example.com",
            mobile="+000000000000",
            best_contact_window="10-18",
            standing_permission=False,
            opted_out=False,
        )
        out += [f"## {label} ({lang})", ""]
        for tpl_id in ("holidays", "event", "stale_hours", "permission"):
            tpl = TEMPLATES[tpl_id]
            items = _items(country, lang) if tpl_id != "stale_hours" else []
            inp = IntroInput(
                template_id=tpl_id,
                language=lang,
                business_name="Kahvila Testi",
                first_name="Maria",  # type: ignore[arg-type]
                facts=intro_facts(
                    tpl_id,
                    lang,
                    items,
                    True,
                    "ask",
                    [{"type": "review"}] if tpl_id == "stale_hours" else [],
                    ["Event nearby: Ice hockey home game", "Venue: Areena", "Expected attendance: about 9800"],
                ),
                tone=tpl.tone,
                goal=tpl.goal,
                sender_name=SENDER,
            )
            subject, intro, short, _ = generate_intro(deps, inp)  # type: ignore[arg-type]
            m = _msg(
                tpl_id,
                tpl.kind,
                lang,
                country,
                intro,
                short,
                subject,
                items=items,
                weekly_shown=week if tpl_id == "stale_hours" else None,
                priority=1.0,
            )  # type: ignore[arg-type]
            if tpl_id == "permission":
                text = compose.compose_permission_body(
                    m, contact, lang, SENDER, {"views": 1234, "calls": 12, "actions": 30}
                )
            else:
                views = compose.views_line(items[0], 340, lang, 20) if items else None
                text = compose.compose_body(m, contact, lang, SENDER, views=views)
            out += [f"### {tpl.label} – email", "", f"Subject: **{subject}**", "", "```text", text, "```", ""]
            if tpl_id == "holidays":
                inform = _msg(
                    tpl_id, "dates", lang, country, intro, short, subject, items=_items(country, lang), mode="inform"
                )  # type: ignore[arg-type]
                out += [
                    "### Holiday hours – inform mode (standing permission)",
                    "",
                    "```text",
                    compose.compose_body(inform, contact, lang, SENDER),
                    "```",
                    "",
                ]
                wa = m.model_copy(update={"channel": "whatsapp"})
                name, params, _, _ = wa_content_fitted(wa, contact, lang)
                sms, _ = sms_text(m, contact, lang)
                out += [
                    "### Holiday hours – WhatsApp (template `" + name + "`)",
                    "",
                    "```text",
                    render_body(name, lang, params),
                    "[" + "] [".join(BUTTONS[name][lang]) + "]",
                    "```",
                    "",
                    "### Holiday hours – SMS",
                    "",
                    "```text",
                    sms,
                    "```",
                    "",
                ]
        applied = [("2026-12-24", "closed"), ("2026-12-31", "10:00-14:00")]
        out += [
            "### Follow-up – applied",
            "",
            "```text",
            compose.compose_followup_applied(
                contact, lang, applied, LISTINGS, None, offer_permission=True, sender_name=SENDER
            ),
            "```",
            "",
            "### Follow-up – declined",
            "",
            "```text",
            compose.compose_followup_declined(contact, lang),
            "```",
            "",
            "### Follow-up – stopped",
            "",
            "```text",
            compose.compose_followup_stopped(lang),
            "```",
            "",
            "### Follow-up – permission granted",
            "",
            "```text",
            compose.compose_followup_permission_granted(contact, lang, applied, LISTINGS),
            "```",
            "",
        ]
    return "\n".join(out)


def main() -> None:  # pragma: no cover
    from app.server.config import load_config

    cfg = load_config()
    if cfg.llm_mode == "vertex":
        from app.server.adapters.llm_vertex import VertexLlm

        llm = VertexLlm(cfg.gcp_project_id or "", cfg.vertex_location, cfg.llm_model)
    else:
        from app.server.adapters.llm_fake import FakeLlm

        llm = FakeLlm()
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(render(llm), encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parents[1])}")


if __name__ == "__main__":
    main()

"""Ports as typing.Protocols, plus the small models they exchange."""

from __future__ import annotations

from datetime import datetime
from typing import Literal, Protocol

from pydantic import BaseModel

from app.core.models import (
    Campaign,
    Contact,
    OutboundMessage,
    Reply,
    YextChange,
)
from app.core.prompts import IntroInput, ParseInput, SimReplyInput


class TargetRow(BaseModel):
    entity_id: str
    date: str
    day_key: str
    day_type: str
    event_id: str | None = None
    country: str
    split: str


class Detection(BaseModel):
    action: Literal["SUGGEST", "NO_ACTION", "FLAG"]
    suggested_hours: str | None = None  # kit hours string when SUGGEST
    shown_hours: str  # what Google shows now
    shown_source: Literal["regular", "exception"]
    basis: str | None = None
    evidence: dict = {}
    confidence: float | None = None  # v2 only
    signals: list[str] = []  # v2 only


class OutgoingMail(BaseModel):
    to: str
    reply_to: str
    subject: str
    text: str
    thread_id: str | None = None
    in_reply_to: str | None = None


class OutsideWindow(Exception):
    """WhatsApp free-form text outside the 24 h customer-service window."""


class WhatsAppError(Exception):
    def __init__(self, code: int | str, message: str):
        super().__init__(f"{code}: {message}")
        self.code = code
        self.message = message


class YextError(Exception):
    pass


class SimUnavailable(Exception):
    pass


class Clock(Protocol):
    def now(self) -> datetime: ...


class Yext(Protocol):
    def get_entity(self, eid: str) -> dict: ...
    def list_entities(self, ids: list[str]) -> list[dict]: ...
    def put_hours(self, eid: str, hours: dict) -> dict: ...
    def listings(self, eid: str) -> list[dict]: ...
    def analytics(self, eid: str, start: str, end: str, metrics: list[str]) -> dict[str, int]: ...


class Findability(Protocol):
    def est_views(self, eid: str, date: str, day_key: str) -> int: ...
    def last_year_views(self, eid: str, day_key: str, country: str, date: str) -> int | None: ...
    def recent_mean(self, eid: str) -> float: ...


class Contacts(Protocol):
    def get(self, eid: str) -> Contact | None: ...
    def raw_language(self, eid: str) -> str | None: ...


class Suggestions(Protocol):
    def rows_for(self, eid: str) -> list[TargetRow]: ...
    def detect(self, row: TargetRow) -> Detection: ...
    def has_history(self, eid: str) -> bool: ...
    def day_info(self, country: str, date: str) -> dict | None: ...
    def event(self, event_id: str) -> dict | None: ...
    def split(self, eid: str) -> str: ...
    def regular_last_changed(self, eid: str) -> str | None: ...
    def peer_change_share(self, eid: str, row: TargetRow) -> tuple[float, int] | None: ...
    def stale_evidence(self, eid: str) -> list[dict]: ...
    def entity_ids(self, split: str | None = None) -> list[str]: ...


class OwnerSim(Protocol):
    def respond(self, eid: str, date: str, proposed_hours: str) -> dict: ...


class Mail(Protocol):
    def send(self, m: OutgoingMail) -> tuple[str, str]: ...
    def list_unprocessed(self, max_n: int) -> list[str]: ...
    def get_raw(self, provider_id: str) -> bytes: ...
    def get_thread_id(self, provider_id: str) -> str | None: ...
    def mark_processed(self, provider_id: str) -> None: ...
    def renew_watch(self) -> str | None: ...


class WhatsApp(Protocol):
    def send_template(self, to_digits: str, name: str, lang: str, params: list[str], payloads: list[str]) -> str: ...
    def send_text(self, to_digits: str, text: str) -> str: ...


class SmsGateway(Protocol):
    def send(self, to: str, text: str, message_id: str | None) -> str: ...


class Llm(Protocol):
    def write_intro(self, inp: IntroInput) -> object: ...
    def parse_reply(self, inp: ParseInput) -> object: ...
    def write_sim_reply(self, inp: SimReplyInput) -> str: ...
    def translate(self, text: str, target: str) -> str: ...


class Store(Protocol):
    def create_campaign(self, c: Campaign) -> None: ...
    def get_campaign(self, cid: str) -> Campaign | None: ...
    def list_campaigns(self, limit: int) -> list[Campaign]: ...
    def update_campaign(self, cid: str, **fields) -> None: ...
    def create_message(self, m: OutboundMessage) -> None: ...
    def get_message(self, mid: str) -> OutboundMessage | None: ...
    def list_messages(self, campaign_id: str) -> list[OutboundMessage]: ...
    def list_messages_for_entity(self, eid: str, limit: int) -> list[OutboundMessage]: ...
    def find_message_by_thread(self, thread_id: str) -> OutboundMessage | None: ...
    def find_message_by_provider_id(self, provider_id: str) -> OutboundMessage | None: ...
    def list_due_escalations(self, now_iso: str) -> list[OutboundMessage]: ...
    def list_due_scheduled(self, now_iso: str) -> list[OutboundMessage]: ...
    def list_replies_for_message(self, message_id: str) -> list[Reply]: ...
    def find_open_messages_by_phone(self, phone_digits: str, channel: str) -> list[OutboundMessage]: ...
    def append_sms(self, entry: dict) -> None: ...
    def list_sms(self, phone: str | None) -> list[dict]: ...
    def update_message(self, mid: str, **fields) -> None: ...
    def claim_message_for_sending(self, mid: str) -> bool: ...
    def create_reply_if_absent(self, r: Reply) -> bool: ...
    def get_reply(self, rid: str) -> Reply | None: ...
    def update_reply(self, rid: str, **fields) -> None: ...
    def list_replies(self, status: str | None, limit: int) -> list[Reply]: ...
    def has_applied_reply(self, message_id: str) -> bool: ...
    def create_change(self, ch: YextChange) -> None: ...
    def get_change(self, change_id: str) -> YextChange | None: ...
    def update_change(self, change_id: str, **fields) -> None: ...
    def try_increment_daily_sends(self, day: str, limit: int) -> bool: ...
    def get_state(self, key: str) -> dict | None: ...
    def set_state(self, key: str, value: dict) -> None: ...
